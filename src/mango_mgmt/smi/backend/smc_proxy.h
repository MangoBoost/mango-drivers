/**
 * typedef smc_proxy_event_callback - the function pointer defintion for the event callback
 * @proxy_id: the associated proxy id.
 * @event_id: the event that cause the callback to be invoked.
 * @arg: void ptr containing the proxy command used to raise request.
 *
 * Return: errno or success code.
 */
typedef int(smc_proxy_event_callback)(uint8_t proxy_id, uint8_t event_id,
				      void *arg);

/*****************************************************************************/
/* Enums                                                                     */
/*****************************************************************************/

/*
 * Per-instance cid name space, not a depth: 64 keeps cyclic reuse far apart;
 * the medium's ring and the card's Limits bound concurrency.
 */
#define SMC_PROXY_MAX_CIDS (64)

/**
 * enum smc_proxy_event - the events generated by the smc proxy layer
 * @SMC_PROXY_EVENT_RESPONSE_COMPLETE: completion event
 * @SMC_PROXY_EVENT_RESPONSE_TIMEOUT: timeout event
 * @SMC_PROXY_EVENT_ORPHAN_ANSWERED: an orphaned command was answered; its cid is
 *	free again and the owner takes back what it lent the request.
 */
enum smc_proxy_event {
	SMC_PROXY_EVENT_RESPONSE_COMPLETE = 0,
	SMC_PROXY_EVENT_RESPONSE_TIMEOUT,
	SMC_PROXY_EVENT_ORPHAN_ANSWERED,

	MAX_SMC_PROXY_EVENT
};

/**
 * enum smc_cmd_state - lifecycle of a command slot in the per-instance pool
 * @SMC_CMD_FREE: slot is free (tag not allocated)
 * @SMC_CMD_RESERVED: tag allocated, request not yet matchable by a response
 * @SMC_CMD_LIVE: request issued and awaiting a response (matchable)
 * @SMC_CMD_DONE: response/timeout/abort handled; tag held until released
 *
 * The owning command claims a slot (FREE -> RESERVED), publishes it once the
 * request is on the wire (RESERVED -> LIVE), and the response/timeout/abort
 * path marks it handled (LIVE -> DONE). The tag stays reserved until the owner
 * releases the slot (-> FREE): within that one claim..release cycle a late or
 * duplicate response is rejected (the slot is no longer LIVE). Across cycles,
 * cyclic tag allocation only makes reuse-collision improbable, not impossible
 * (the same guarantee level as the legacy cyclic cid pool).
 *
 * A LIVE command its waiter gave up on may be orphaned instead: it stays LIVE
 * and its tag stays taken until its answer lands, which frees both at once.
 */
enum smc_cmd_state {
	SMC_CMD_FREE = 0,
	SMC_CMD_RESERVED,
	SMC_CMD_LIVE,
	SMC_CMD_DONE,
};

/******************************************************************************************/
/* Structs                                                                                */
/******************************************************************************************/

/* Opaque proxy instance; owned by the transport layer (see smc_proxy.c). */
struct smc_proxy_instance;

/**
 * struct smi_pending: one slot in a proxy instance's pre-allocated
 *     command pool, indexed by its cid (tag). Claimed per submission via
 *     smc_proxy_cid_claim() and returned via smc_proxy_tag_release(); never freed
 *     individually (the pool lives for the proxy instance's lifetime).
 *
 * @state: slot lifecycle (see enum smc_cmd_state); guarded by the instance lock
 * @cmd_complete: conditional variable to be signalled via callback
 * @cmd_timeout_jiffies: jiffies to wait for response until timing out command
 * @cmd_rcode: the return code
 * @cmd_cid: the unique id (tag) associated with the command; also the pool index
 * @completion: the answer exactly as it arrived off the ring. What its bytes
 *              mean belongs to the generation that built the request, so the
 *              row's reader casts it and this layer never does.
 * @cmd_arg: the owner, for an answer that lands after its waiter left
 * @inst: owning proxy instance (set on claim); used instead of a global lookup
 * @cmd_suppress_dbg: flag to indicate debug suppressed for command
 * @timed_out: boolean indicating if this command timed out
 * @orphaned: its waiter gave up and its answer, when it lands, frees the cid
 */
struct smi_pending {
	enum smc_cmd_state state;
	struct completion cmd_complete;
	uintptr_t cmd_timeout_jiffies;
	int cmd_rcode;
	uint16_t cmd_cid;
	uint8_t completion[SMI_COMPLETION_FRAME_BYTES];
	void *cmd_arg;
	struct smc_proxy_instance *inst;
	bool cmd_suppress_dbg;
	bool timed_out;
	/* This slot expired and was given up on, so an answer may still land on
	 * it. Distinguishes a late answer from one for a command never sent. */
	bool expired;
	bool orphaned;
};

/******************************************************************************************/
/* Public Functions                                                                       */
/******************************************************************************************/

/**
 * smc_proxy_init() - Initialise the smc proxy layer for one transport instance.
 *
 * @dev: device used to devm-allocate the instance (lifetime = device).
 * @fw_if_handle: handle to the fw interface to open.
 *
 * Allocates the proxy instance (and its command pool) under @dev's devm scope,
 * opens the FAL handle and starts the response thread. Because the instance is
 * device-lived, smc_proxy_close() stops the service but does NOT free it; the
 * memory is reclaimed by devm at device detach, after all submitters have gone.
 *
 * Return: the proxy instance, or NULL on failure.
 */
struct smc_proxy_instance *smc_proxy_init(struct device *dev,
					  FW_IF_CFG *fw_if_handle,
					  uint32_t tx_capacity);

/**
 * smc_proxy_bind_callback() - Bind in an event callback
 *
 * @inst: the proxy instance
 * @event_cb: callback to be invoked when an event is generated
 *
 * Return: The errno return code
 */
int smc_proxy_bind_callback(struct smc_proxy_instance *inst,
			    smc_proxy_event_callback *event_cb);

/**
 * smc_proxy_close() - Stop the proxy service (drain in-flight, stop the response
 *                     thread, close the FAL handle).
 *
 * @inst: the proxy instance
 *
 * Does NOT free the instance (devm-owned; freed at device detach). Idempotent:
 * a second call is a no-op, so the fatal-event and remove paths may both close.
 *
 * Return: 0; -EPERM when not open; -EIO when the FAL handle did not close.
 */
int smc_proxy_close(struct smc_proxy_instance *inst);

/**
 * smc_proxy_submit() - put one filled request frame on the ring.
 * @cmd: the claimed slot; it owns the cid the frame already carries.
 * @frame: the frame, header and payload both already stamped by its generation.
 * @len: frame bytes to write.
 *
 * This layer carries bytes: it does not build the frame and does not read the
 * answer. A full ring is backpressure and is waited out against the command's
 * own deadline.
 *
 * Return: 0, or the errno the write failed with.
 */
int smc_proxy_submit(struct smi_pending *cmd, const void *frame, uint16_t len);

/**
 * smc_proxy_deadline_pending() - true while a live command still has time left
 *                                on the deadline its row granted it.
 * @inst: the proxy instance
 */
bool smc_proxy_deadline_pending(struct smc_proxy_instance *inst);

/**
 * smc_proxy_orphan() - Give up waiting while keeping the command's cid taken.
 * @cmd: a command whose waiter is leaving.
 *
 * For a card that answers every request: no later request matches it, and its
 * answer frees the cid (SMC_PROXY_EVENT_ORPHAN_ANSWERED). Do not release it.
 *
 * Return: true when orphaned; false when it was no longer live (answered or
 *         drained meanwhile), and the caller releases it as usual.
 */
bool smc_proxy_orphan(struct smi_pending *cmd);

/**
 * smc_proxy_request_abort() - Abort a request already in progress
 *
 * @cmd: the proxy command structure
 *
 * Return: The errno return code
 */
int smc_proxy_request_abort(struct smi_pending *cmd);

/**
 * smc_proxy_drain_all() - Force-drain every in-flight command on @inst.
 *
 * @inst: the proxy instance
 *
 * Used by the shutdown path to wake any waiter blocked in wait_for_completion_*()
 * so kthread_stop() can proceed. Each in-flight command is dequeued and notified
 * via the registered event callback with -ESHUTDOWN.
 *
 * Return: 0 on success, negative errno otherwise.
 */
int smc_proxy_drain_all(struct smc_proxy_instance *inst);

/**
 * smc_proxy_cid_claim() - Claim a command slot (tag) from the proxy instance pool.
 *
 * @inst: the proxy instance
 *
 * Allocates a cid/tag and returns the pre-allocated command slot for it,
 * re-initialised and ready to populate. The slot must be returned with
 * smc_proxy_tag_release() once the caller is done with any response.
 *
 * Return: the command slot, or NULL if the instance is gone or the tag pool is
 * exhausted.
 */
struct smi_pending *smc_proxy_cid_claim(struct smc_proxy_instance *inst);

/**
 * smc_proxy_tag_release() - Return a command slot claimed via smc_proxy_cid_claim().
 *
 * @cmd: the proxy command structure
 *
 * Frees the cid/tag for reuse. Must be the last proxy call for @cmd (after the
 * response has been consumed), as it permits the tag to be re-allocated.
 */
void smc_proxy_tag_release(struct smi_pending *cmd);

#endif /* _SMC_PROXY_H_ */
